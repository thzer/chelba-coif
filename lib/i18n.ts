export type Lang = "fr" | "en" | "ar";

export const LANGS: { code: Lang; label: string; locale: string; dir: "ltr" | "rtl" }[] = [
  { code: "fr", label: "FR", locale: "fr-FR", dir: "ltr" },
  { code: "en", label: "EN", locale: "en-GB", dir: "ltr" },
  { code: "ar", label: "AR", locale: "ar-TN", dir: "rtl" },
];

export const DEFAULT_LANG: Lang = "fr";

export function isLang(value: unknown): value is Lang {
  return value === "fr" || value === "en" || value === "ar";
}

export function langMeta(lang: Lang) {
  return LANGS.find((l) => l.code === lang) ?? LANGS[0];
}

